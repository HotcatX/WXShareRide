import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

// Generated copies are standalone deployment artifacts, not separately edited
// handlers. No private key belongs to the source or generated public files.
const require = createRequire(import.meta.url);
const { QUERY_BUNDLES } = require('../../../cloudfunctions/compat/query-bridge.js');
const bridge = await readFile(new URL('../../../cloudfunctions/compat/query-bridge.js', import.meta.url), 'utf8');
const context = await readFile(new URL('../../../cloudfunctions/backend/context.js', import.meta.url), 'utf8');
for (const [name, definition] of Object.entries(QUERY_BUNDLES)) {
  const path = new URL(`../../../cloudfunctions/${name}/`, import.meta.url);
  const index = `// Generated by services/backend/scripts/sync-cloud-queries.mjs.\n'use strict'\n`
    + `const fs = require('node:fs')\nconst path = require('node:path')\n`
    + `const { getIdentity } = require('./context')\nconst { createQueryHandler } = require('./query-bridge')\n`
    + `function getKey() {\n  const value = fs.readFileSync(path.join(__dirname, 'query-bridge.secret'), 'utf8').trim()\n`
    + `  if (!/^[a-f0-9]{64}$/.test(value)) throw Error('QUERY_UNAVAILABLE')\n  return Buffer.from(value, 'hex')\n}\n`
    + `exports.main = createQueryHandler({ action: ${JSON.stringify(definition.action)}, fields: ${JSON.stringify(definition.fields)}, getIdentity, getKey })\n`;
  const pkg = { name: `linkx-query-${name.toLowerCase()}`, version: '1.0.0', private: true,
    main: 'index.js', type: 'commonjs', dependencies: {} };
  const lock = { name: pkg.name, version: pkg.version, lockfileVersion: 3, requires: true,
    packages: { '': { name: pkg.name, version: pkg.version } } };
  const files = { 'index.js': index, 'context.js': context, 'query-bridge.js': bridge,
    'package.json': `${JSON.stringify(pkg, null, 2)}\n`, 'package-lock.json': `${JSON.stringify(lock, null, 2)}\n` };
  if (!process.argv.includes('--check')) await mkdir(path, { recursive: true });
  for (const [file, content] of Object.entries(files)) {
    const target = new URL(file, path);
    if (process.argv.includes('--check')) {
      if (await readFile(target, 'utf8') !== content) throw Error(`Stale legacy query artifact: ${name}/${file}`);
    } else await writeFile(target, content);
  }
}
