import { readFile, writeFile } from 'node:fs/promises';

// Only config/locationCatalog.json is edited by hand. Keep deployment copies
// deterministic; the mini-program needs a JS module and backend Docker packages
// only services/backend. The collector also uses its own deployment copy.
// No export, credential or private data enters these assets.
const source = new URL('../../../config/locationCatalog.json', import.meta.url);
const backend = new URL('../src/locations/catalog.generated.json', import.meta.url);
const mini = new URL('../../../utils/locationCatalog.generated.js', import.meta.url);
const parsed = JSON.parse(await readFile(source, 'utf8'));
const json = JSON.stringify(parsed, null, 2) + '\n';
const js = '// Generated by services/backend/scripts/sync-location-catalog.mjs; edit config/locationCatalog.json.\nmodule.exports = ' + json;
// Keep lookup behavior in utils/placeCatalog.js; inline only its public facts
// for the standalone collector package, which cannot require the repository root.
const helper = await readFile(new URL('../../../utils/placeCatalog.js', import.meta.url), 'utf8');
const header = "const { placeCatalogVersion: CATALOG_VERSION, fixedPlaces: FIXED_PLACES } = require('./locationCatalog.generated.js')\n";
if (!helper.startsWith(header)) throw new Error('Unexpected place catalog helper entry; update its generator explicitly');
const standalone = '// Generated by services/backend/scripts/sync-location-catalog.mjs; edit config/locationCatalog.json and utils/placeCatalog.js.\n'
  + `const CATALOG_VERSION = ${JSON.stringify(parsed.placeCatalogVersion)}\n`
  + `const FIXED_PLACES = ${JSON.stringify(parsed.fixedPlaces, null, 2)}\n`
  + helper.slice(header.length);
const assets = [[backend, json], [mini, js],
  [new URL('../../analytics-collector/src/place-catalog.cjs', import.meta.url), standalone]];
for (const [path, content] of assets) {
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) {
      throw new Error(`Location asset ${path.pathname} is stale; run node services/backend/scripts/sync-location-catalog.mjs`);
    }
  } else await writeFile(path, content);
}
