import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../src/templates/identity.cjs', import.meta.url);
const target = new URL('../../../utils/compat/templateIdentity.generated.js', import.meta.url);
const value = '// Generated by services/backend/scripts/sync-template-identity.mjs; edit services/backend/src/templates/identity.cjs.\n' + await readFile(source, 'utf8');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== value) throw Error('Template identity asset is stale');
} else await writeFile(target, value);
