import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';

// Standalone CloudBase bundles cannot import the mini-program's configuration.
// Generate their handoff value from the same source; never edit either copy.
const require = createRequire(import.meta.url);
const { mode } = require('../../../config/backend.js');
if (!['cloudbase', 'server'].includes(mode)) throw new Error('Invalid backend authority');
const content = '// Generated by services/backend/scripts/sync-cloud-authority.mjs; edit config/backend.js.\n'
  + `module.exports = '${mode}'\n`;
for (const name of ['backend', 'statistics']) {
  const path = new URL(`../../../cloudfunctions/${name}/authority.js`, import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Stale ${name} authority asset`);
  } else await writeFile(path, content);
}
